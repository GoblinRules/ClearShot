def ui_icon(
    name: str,
    color: str | QColor = "#f5f7fb",
    accent: str | QColor = "#0099ff",
    sizes: tuple[int, ...] = (16, 20, 24, 32),
) -> QIcon:
    """Build a scalable-looking QIcon from painted pixmaps."""
    icon = QIcon()
    for size in sizes:
        pixmap = QPixmap(QSize(size, size))
        pixmap.fill(Qt.GlobalColor.transparent)

        painter = QPainter(pixmap)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        paint_icon(painter, name, QRectF(0, 0, size, size), color, accent)
        painter.end()

        icon.addPixmap(pixmap)
    return icon


def paint_icon(
    painter: QPainter,
    name: str,
    rect: QRectF,
    color: str | QColor = "#f5f7fb",
    accent: str | QColor = "#0099ff",
) -> None:
    """Paint one named icon inside rect."""
    name = _normalize_name(name)
    r = QRectF(rect).adjusted(
        rect.width() * 0.08,
        rect.height() * 0.08,
        -rect.width() * 0.08,
        -rect.height() * 0.08,
    )
    fg = QColor(color)

    painter.save()
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)

    if name in MDI_PATHS:
        _draw_mdi_icon(painter, r, MDI_PATHS[name], fg)
    else:
        _draw_text_glyph(painter, r, name[:1].upper() or "?", fg, 0.62)

    painter.restore()


def _normalize_name(name: str) -> str:
    aliases = {
        "highlight": "filled_rect",
        "filled": "filled_rect",
        "monitor": "monitor",
        "open_folder": "folder",
        "edit": "editor",
        "exit": "close",
        "color": "palette",
        "recording": "record",
        "screen_record": "record",
        "stop_recording": "stop",
    }
    key = name.lower().strip().replace("-", "_").replace(" ", "_")
    return aliases.get(key, key)


def _draw_mdi_icon(painter: QPainter, rect: QRectF, path_data: str, color: QColor) -> None:
    opacity = max(0.0, min(1.0, color.alphaF()))
    svg = f"""
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">
      <path fill="{color.name()}" fill-opacity="{opacity:.3f}" d="{path_data}"/>
    </svg>
    """
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    renderer.render(painter, rect)


def _draw_text_glyph(painter: QPainter, rect: QRectF, text: str, color: QColor, scale: float) -> None:
    painter.setPen(QPen(color))
    painter.setBrush(Qt.BrushStyle.NoBrush)
    font = QFont("Segoe UI")
    font.setBold(True)
    font.setPixelSize(max(8, int(min(rect.width(), rect.height()) * scale)))
    painter.setFont(font)
    painter.drawText(rect, Qt.AlignmentFlag.AlignCenter, text)
